#!/usr/bin/env python3
"""Adapt scikit-learn's "Choosing the right estimator" map for the deck.

    python3 day1/intro/src/sklearn-map.py day1/intro/src/ml_map.upstream.svg \
        day1/intro/images/sklearn-ml-map.svg

The upstream file is `doc/images/ml_map.svg` of scikit-learn (main, fetched
2026-10-14), a draw.io export under the BSD 3-Clause licence, whose text sits in
`foreignObject` blocks that browsers render. Changes, recorded here as the
licence asks: the draw.io model (`content=`), the fixed size, the links to the
estimator pages (relative, so broken inside the deck) and the draw.io fallback
note are removed; a highlight layer is added that walks the path from START to
the classification region in four `data-step`s (ext/stepwise-svg.js), drawn in
the theme's accent (ext/svg-theme.js).
"""

import re
import sys
from pathlib import Path

ACCENT = "#00609c"


def ring(cx, cy, step):
    return (f'<ellipse class="accent-stroke" data-step="{step}" cx="{cx}" cy="{cy}" rx="50" ry="45" '
            f'fill="none" stroke="{ACCENT}" stroke-width="7"/>')


LAYER = "\n".join([
    "<!-- Highlight layer added for the EAD deck (Oscar Esteban, CC BY 4.0). -->",
    '<g pointer-events="none">',
    ring(836, 130, 1), ring(756, 240, 1),   # START, then more than 50 samples
    ring(726, 350, 2),                      # predicting a category: yes
    ring(636, 440, 3),                      # do you have labeled data: yes
    f'<rect class="accent-stroke" data-step="4" x="8" y="87" width="576" height="326" rx="52" '
    f'fill="none" stroke="{ACCENT}" stroke-width="8"/>',
    "</g>",
])


def main(src: Path, out: Path) -> int:
    s = src.read_text(encoding="utf-8")
    root = re.search(r"<svg [^>]*>", s)
    tag = re.sub(r'\s(content|width|height)="[^"]*"', "", root.group(0))
    s = s[:root.start()] + tag + s[root.end():]
    s = re.sub(r'<switch><g requiredFeatures="[^"]*"/><a transform="translate\(0,-5\)"[^>]*>'
               r'<text[^>]*>Text is not SVG - cannot display</text></a></switch>', "", s)
    s = re.sub(r"<a [^>]*>", "<g>", s).replace("</a>", "</g>")
    s = s.replace("<!-- Do not edit this file with editors other than draw.io -->",
                  "<!-- scikit-learn, Choosing the right estimator (doc/images/ml_map.svg). (c) 2007-2026 "
                  "the scikit-learn developers, BSD 3-Clause (see sklearn-ml-map.LICENSE.txt); the cheat sheet "
                  "was first drawn by Andreas Mueller. Modified for the EAD deck, see day1/intro/src/sklearn-map.py. -->")
    s = s.replace("</svg>", LAYER + "\n</svg>")
    assert "Text is not SVG" not in s and "xlink:href=\"./modules" not in s and 'content="' not in s[:3000]
    out.write_text(s, encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    raise SystemExit(main(Path(sys.argv[1]), Path(sys.argv[2])))
